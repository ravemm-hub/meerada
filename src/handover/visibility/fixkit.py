from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from handover.visibility.audit import Audit, Fetch, audit, http_get
from handover.visibility.compare import compare, same_business
from handover.visibility.consensus import rank
from handover.visibility.experiments import load_experiments
from handover.visibility.gap import cited_hosts
from handover.visibility.google import load_snapshot
from handover.visibility.questions import BY_ID
from handover.visibility.state import State

_LATIN = re.compile(r"[A-Za-z]")
OWNER_SIDE = {
    "google.com": "Google Business Profile: add an English business name variant and an English description; pick the exact category; same phone and address as your site.",
    "easy.co.il": "easy.co.il: claim the listing (owner SMS verification) and complete hours, services and photos.",
    "tripadvisor.com": "Tripadvisor: register the business under Owner Centre; keep the name and address identical to Google.",
    "tripadvisor.co.uk": "Tripadvisor: register the business under Owner Centre; keep the name and address identical to Google.",
    "zocdoc.com": "Zocdoc: list the practice (paid listing) — the engines read it for New York dentists.",
    "ontopo.com": "Ontopo: keep the restaurant page current (menu, hours); the engines cite it for Tel Aviv restaurants.",
    "yelp.com": "Yelp: claim the free listing and complete every field; Yelp feeds all three engines.",
    "timeout.com": "Time Out: an editorial list — Meerada pitches the facts; you can send press photos and a one-paragraph description to the editor.",
    "secrettelaviv.com": "Secret Tel Aviv: an editorial list — Meerada pitches the facts; a public post from you with photos helps.",
    "atly.com": "Atly: a community list — ask happy customers who use Atly to save your place.",
    "wanderlog.com": "Wanderlog: built from Google data — fix Google first.",
    "instagram.com": "Instagram: put the English business name, city and phone in the bio; the engines read it as a page.",
    "facebook.com": "Facebook: complete the page's About section in English and the local language.",
}


def _lift_for(exp: dict[str, Any], state: State) -> tuple[list[str], list[tuple[str, int]]]:
    """Lift steps for this business from its question's comparison, and the cited hosts."""
    qid = exp["queries"][0]
    answers = [a for a in state.answers if a.query_id == qid]
    hosts = cited_hosts(answers)
    snap = load_snapshot(qid)
    steps: list[str] = []
    if snap is not None and any(not a.error for a in answers):
        cmp = compare(rank(answers), snap)
        names = [exp["business"], *exp.get("aliases", [])]
        for row in (cmp or {}).get("google_only", []):
            if any(same_business(n, row["name"]) for n in names):
                steps = list(row["lift"])
                break
        if not steps and cmp and cmp["google_only"]:
            steps = list(cmp["google_only"][0]["lift"])
    return steps, hosts


def _draft_for(exp: dict[str, Any], drafts_dir: Path) -> dict[str, Any] | None:
    domain = (exp.get("domain") or "").lower()
    for path in sorted(drafts_dir.glob("*.json")) if drafts_dir.exists() else []:
        for p in json.loads(path.read_text(encoding="utf-8")).get("profiles", []):
            if domain and domain in (p.get("website") or ""):
                return dict(p)
    return None


def render_fixkit(
    exp: dict[str, Any],
    a: Audit | None,
    steps: list[str],
    hosts: list[tuple[str, int]],
    draft: dict[str, Any] | None,
    today: str,
) -> str:
    q = BY_ID[exp["queries"][0]]
    name = exp["business"]
    facts = draft or {}

    def todo(v: object) -> str:
        return str(v) if v else "TODO — state it in plain text on the site"

    lines = [
        f"# Fix kit for {name} — the AI engines and your website",
        "",
        f"Generated by Meerada on {today} for the question: “{q.text}” ({q.city}).",
        "",
        "**How to use this file:** paste it into Claude or ChatGPT (or send it to your web developer) with the sentence: "
        "“Apply these changes to our website; keep every fact exactly as written; ask me for anything marked TODO.” "
        "Meerada re-measures the question every week and sends you the numbers.",
        "",
        "## 1. Facts the engines must find as plain text (not only in images or scripts)",
        "",
        f"- Business name, exactly as on Google: **{name}**"
        + (
            f" — English form: {facts.get('name')}"
            if facts.get("name")
            and facts.get("name") != name
            and _LATIN.search(str(facts.get("name")))
            else " — English form: TODO (the name customers would type in English)"
        ),
        f"- Phone: {todo(facts.get('phone'))}",
        f"- Address: {todo(facts.get('address'))}",
        f"- Opening hours: {todo(facts.get('hours'))}",
        f"- Prices or price ranges: {todo(facts.get('prices'))}",
        f"- Services: {', '.join(facts.get('services') or []) or 'TODO — list what you do, one line each'}",
        f"- Languages spoken: {', '.join(facts.get('languages') or []) or 'TODO'}",
        "",
        "## 2. Changes to the website, in order",
        "",
    ]
    if a is None:
        lines.append(
            "- The site could not be fetched (TLS or DNS failure). An engine cannot cite a page that does not load. Fix hosting first; everything else waits."
        )
    else:
        lines.append(f"Entity audit score today: {a.score}/100.")
        lines.append("")
        lines += [f"{i}. {f}" for i, f in enumerate(a.fixes(), start=1)] or [
            "- Nothing blocking found on the home page. Keep facts current."
        ]
    lines += ["", "## 3. Where the engines read for this question — and your part on each", ""]
    for host, n in hosts:
        action = OWNER_SIDE.get(
            host,
            f"{host}: make sure the business appears there with the same name, phone and address as on Google.",
        )
        lines.append(f"- {host} (cited {n}x): {action}")
    if not hosts:
        lines.append(
            "- No citations recorded yet for this question; the business sites themselves are the sources."
        )
    lines += [
        "",
        "## 4. A paragraph to paste on your home page (English; add the same in your language)",
        "",
    ]
    summary = facts.get("summary") or f"{name} is a {q.category} in {q.city}."
    services = "; ".join(facts.get("services") or [])[:300]
    lines.append(
        f"> {summary} {('Services: ' + services + '.') if services else ''} Phone {facts.get('phone') or 'TODO'}. {facts.get('address') or 'Address TODO'}. Open {facts.get('hours') or 'hours TODO'}."
    )
    lines += ["", "## 5. What Meerada does on its side", ""]
    lines += [f"- {s}" for s in steps] or [
        "- Factual entity page on meerada.app, inclusion in the question's guide if the quality bar is met, weekly re-measurement."
    ]
    lines += [
        "",
        "_Facts only. Nothing here asks for reviews or ratings; the engines reward being present and consistent, not being praised._",
        "",
    ]
    return "\n".join(lines)


def write_fixkits(
    experiments_path: Path,
    state: State,
    out_dir: Path,
    fetch: Fetch = http_get,
    drafts_dir: Path = Path("data/profiles/drafts"),
) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    today = datetime.now(tz=UTC).date().isoformat()
    written: list[Path] = []
    experiments = load_experiments(experiments_path)
    claimed = experiments_path.with_name("pilots.json")
    if claimed != experiments_path:
        experiments += load_experiments(claimed)
    for e in experiments:
        exp = e.model_dump(mode="json")
        if exp.get("control") or not exp.get("domain"):
            continue
        try:
            a: Audit | None = audit(exp["domain"], exp["business"], fetch)
        except Exception:  # unreachable site: the kit says so
            a = None
        steps, hosts = _lift_for(exp, state)
        text = render_fixkit(exp, a, steps, hosts, _draft_for(exp, drafts_dir), today)
        path = out_dir / f"{exp['id']}-fixkit.md"
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
