"""The fix kit — the owner's side of the lift, as one file they can hand to an AI or a developer.

Built per pilot from what the machine already knows: the entity audit of their site (what
an engine cannot read there), the pages the engines cite for their question (where they
must be present), the lift steps for their category, and the profile draft (the facts to
state in plain text). The file is written so that "paste this into Claude or ChatGPT and
ask it to apply it to our site" works: facts first, then ordered changes, then the
paragraph to paste. Nothing is sent from here.

    meerada visibility fixkit --experiments data/experiments.json --state visibility_state.json --out out/pilots
"""

